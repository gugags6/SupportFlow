import { BadRequestException, Injectable, NotFoundException } from '@nestjs/common';
import { Prisma, Ticket, TicketPriority, TicketStatus } from '@prisma/client';
import { PrismaService } from '../../database/prisma.service';
import { CreateTicketDto } from './dto/create-ticket.dto';
import { ListTicketsQueryDto } from './dto/list-tickets-query.dto';
import { UpdateTicketDto } from './dto/update-ticket.dto';
import { PaginatedTicketsEntity } from './entities/paginated-tickets.entity';

/** Prisma error code raised when a record targeted by update/delete does not exist. */
const RECORD_NOT_FOUND = 'P2025';

@Injectable()
export class TicketsService {
  constructor(private readonly prisma: PrismaService) {}

  /**
   * id and ticketNumber are generated by PostgreSQL (gen_random_uuid() and a
   * sequence-backed generate_ticket_number()), so concurrent requests can never
   * receive the same ticket number. status defaults to OPEN, priority to MEDIUM.
   */
  create(dto: CreateTicketDto): Promise<Ticket> {
    return this.prisma.ticket.create({
      data: {
        title: dto.title,
        description: dto.description,
        priority: dto.priority ?? TicketPriority.MEDIUM,
        status: TicketStatus.OPEN,
      },
    });
  }

  async findAll(query: ListTicketsQueryDto): Promise<PaginatedTicketsEntity> {
    const { page, limit, status, priority, search, order } = query;

    const where: Prisma.TicketWhereInput = {
      deletedAt: null,
      ...(status && { status }),
      ...(priority && { priority }),
      ...(search && { title: { contains: search, mode: Prisma.QueryMode.insensitive } }),
    };

    const [data, total] = await this.prisma.$transaction([
      this.prisma.ticket.findMany({
        where,
        // id as tie-breaker keeps pagination stable for identical timestamps.
        orderBy: [{ createdAt: order }, { id: order }],
        skip: (page - 1) * limit,
        take: limit,
      }),
      this.prisma.ticket.count({ where }),
    ]);

    return {
      data,
      meta: { page, limit, total, totalPages: Math.ceil(total / limit) },
    };
  }

  async findOne(id: string): Promise<Ticket> {
    const ticket = await this.prisma.ticket.findFirst({ where: { id, deletedAt: null } });
    if (!ticket) {
      throw this.notFound(id);
    }
    return ticket;
  }

  update(id: string, dto: UpdateTicketDto): Promise<Ticket> {
    if (dto.title === undefined && dto.description === undefined) {
      throw new BadRequestException({
        message: 'Validation failed',
        errors: ['at least one of title or description must be provided'],
      });
    }
    return this.updateActive(id, { title: dto.title, description: dto.description });
  }

  updateStatus(id: string, status: TicketStatus): Promise<Ticket> {
    return this.updateActive(id, { status });
  }

  updatePriority(id: string, priority: TicketPriority): Promise<Ticket> {
    return this.updateActive(id, { priority });
  }

  async remove(id: string): Promise<void> {
    await this.updateActive(id, { deletedAt: new Date() });
  }

  /**
   * Updates a ticket only if it exists and is not soft-deleted. The check and
   * the write happen in a single statement (UPDATE ... WHERE id = $1 AND
   * deleted_at IS NULL), so there is no read-then-write race.
   */
  private async updateActive(id: string, data: Prisma.TicketUpdateInput): Promise<Ticket> {
    try {
      return await this.prisma.ticket.update({ where: { id, deletedAt: null }, data });
    } catch (error) {
      if (
        error instanceof Prisma.PrismaClientKnownRequestError &&
        error.code === RECORD_NOT_FOUND
      ) {
        throw this.notFound(id);
      }
      throw error;
    }
  }

  private notFound(id: string): NotFoundException {
    return new NotFoundException(`Ticket with id ${id} not found`);
  }
}
