import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Patch,
  Post,
  Query,
} from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiCreatedResponse,
  ApiInternalServerErrorResponse,
  ApiNoContentResponse,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
} from '@nestjs/swagger';
import { Ticket } from '@prisma/client';
import { ErrorResponseDto } from '../../common/dto/error-response.dto';
import { parseUuid } from '../../common/pipes/parse-uuid.pipe';
import { CreateTicketDto } from './dto/create-ticket.dto';
import { ListTicketsQueryDto } from './dto/list-tickets-query.dto';
import { UpdateTicketPriorityDto } from './dto/update-ticket-priority.dto';
import { UpdateTicketStatusDto } from './dto/update-ticket-status.dto';
import { UpdateTicketDto } from './dto/update-ticket.dto';
import { PaginatedTicketsEntity } from './entities/paginated-tickets.entity';
import { TicketEntity } from './entities/ticket.entity';
import { TicketsService } from './tickets.service';

const ID_PARAM = { name: 'id', format: 'uuid', description: 'Ticket UUID.' } as const;

@ApiTags('Tickets')
@ApiInternalServerErrorResponse({ description: 'Unexpected server error.', type: ErrorResponseDto })
@Controller('tickets')
export class TicketsController {
  constructor(private readonly ticketsService: TicketsService) {}

  @Post()
  @ApiOperation({
    summary: 'Create a ticket',
    description:
      'Creates a ticket with status OPEN. Priority defaults to MEDIUM. The UUID and the ' +
      'ticket number (TCK-000001) are generated by the server.',
  })
  @ApiCreatedResponse({ description: 'Ticket created.', type: TicketEntity })
  @ApiBadRequestResponse({ description: 'Validation failed.', type: ErrorResponseDto })
  create(@Body() dto: CreateTicketDto): Promise<Ticket> {
    return this.ticketsService.create(dto);
  }

  @Get()
  @ApiOperation({
    summary: 'List tickets',
    description:
      'Returns a paginated list of non-deleted tickets. Supports filtering by status and ' +
      'priority, case-insensitive title search and sorting by creation date.',
  })
  @ApiOkResponse({ description: 'Paginated list of tickets.', type: PaginatedTicketsEntity })
  @ApiBadRequestResponse({ description: 'Invalid query parameters.', type: ErrorResponseDto })
  findAll(@Query() query: ListTicketsQueryDto): Promise<PaginatedTicketsEntity> {
    return this.ticketsService.findAll(query);
  }

  @Get(':id')
  @ApiOperation({ summary: 'Retrieve a ticket by UUID' })
  @ApiParam(ID_PARAM)
  @ApiOkResponse({ description: 'The ticket.', type: TicketEntity })
  @ApiBadRequestResponse({ description: 'Invalid UUID.', type: ErrorResponseDto })
  @ApiNotFoundResponse({ description: 'Ticket not found or deleted.', type: ErrorResponseDto })
  findOne(@Param('id', parseUuid()) id: string): Promise<Ticket> {
    return this.ticketsService.findOne(id);
  }

  @Patch(':id')
  @ApiOperation({
    summary: 'Update ticket title and/or description',
    description:
      'Only title and description can be changed here. Any other field is rejected with 400. ' +
      'Use the dedicated endpoints to change status or priority.',
  })
  @ApiParam(ID_PARAM)
  @ApiOkResponse({ description: 'Updated ticket.', type: TicketEntity })
  @ApiBadRequestResponse({
    description: 'Invalid UUID, validation failed, empty body or forbidden field.',
    type: ErrorResponseDto,
  })
  @ApiNotFoundResponse({ description: 'Ticket not found or deleted.', type: ErrorResponseDto })
  update(@Param('id', parseUuid()) id: string, @Body() dto: UpdateTicketDto): Promise<Ticket> {
    return this.ticketsService.update(id, dto);
  }

  @Patch(':id/status')
  @ApiOperation({ summary: 'Change ticket status' })
  @ApiParam(ID_PARAM)
  @ApiOkResponse({ description: 'Updated ticket.', type: TicketEntity })
  @ApiBadRequestResponse({ description: 'Invalid UUID or status.', type: ErrorResponseDto })
  @ApiNotFoundResponse({ description: 'Ticket not found or deleted.', type: ErrorResponseDto })
  updateStatus(
    @Param('id', parseUuid()) id: string,
    @Body() dto: UpdateTicketStatusDto,
  ): Promise<Ticket> {
    return this.ticketsService.updateStatus(id, dto.status);
  }

  @Patch(':id/priority')
  @ApiOperation({ summary: 'Change ticket priority' })
  @ApiParam(ID_PARAM)
  @ApiOkResponse({ description: 'Updated ticket.', type: TicketEntity })
  @ApiBadRequestResponse({ description: 'Invalid UUID or priority.', type: ErrorResponseDto })
  @ApiNotFoundResponse({ description: 'Ticket not found or deleted.', type: ErrorResponseDto })
  updatePriority(
    @Param('id', parseUuid()) id: string,
    @Body() dto: UpdateTicketPriorityDto,
  ): Promise<Ticket> {
    return this.ticketsService.updatePriority(id, dto.priority);
  }

  @Delete(':id')
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiOperation({
    summary: 'Soft-delete a ticket',
    description:
      'Sets deletedAt to the current timestamp. The record is kept in the database but is ' +
      'no longer returned by any endpoint.',
  })
  @ApiParam(ID_PARAM)
  @ApiNoContentResponse({ description: 'Ticket deleted.' })
  @ApiBadRequestResponse({ description: 'Invalid UUID.', type: ErrorResponseDto })
  @ApiNotFoundResponse({
    description: 'Ticket not found or already deleted.',
    type: ErrorResponseDto,
  })
  remove(@Param('id', parseUuid()) id: string): Promise<void> {
    return this.ticketsService.remove(id);
  }
}
